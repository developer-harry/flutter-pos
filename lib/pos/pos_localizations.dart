String localizePosText(Locale locale, String japanese) {
  final translations = switch (locale.languageCode) {
    'en' => _englishTranslations,
    'my' => _myanmarTranslations,
    _ => null,
  };
  if (translations == null) return japanese;
  final exactTranslation = translations[japanese];
  if (exactTranslation != null) return exactTranslation;
  for (final translation in translations.entries) {
    if (japanese.startsWith(translation.key)) {
      return '${translation.value}${japanese.substring(translation.key.length)}';
    }
  }
  return japanese;
}

extension PosLocalizations on BuildContext {
  String posText(String japanese) =>
      localizePosText(Localizations.localeOf(this), japanese);
}
